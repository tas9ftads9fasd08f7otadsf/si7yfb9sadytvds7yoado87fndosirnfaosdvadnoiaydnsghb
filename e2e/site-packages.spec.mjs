import { test, expect } from "@playwright/test";
import { addFrom } from "./phone.mjs";
import { mockCloud, recordCoreAsks, recordCoreCalls } from "./mock-cloud.mjs";

const TATRAS = "6F1E2A10-0000-4000-8000-000000000001";

// 204 Add layer's Riki packages were missing on the site; the core lists them, and a ticked one is added as an edit
test("Add layer lists the Riki packages the core reads and adds the ticked one", async ({ page }) => {
  const calls = await recordCoreCalls(page, ["riki_packages"]);
  const asks = await recordCoreAsks(page);
  const cloud = await mockCloud(page, { signedIn: true });
  await page.goto("./");
  await page.locator("#current .hero").waitFor();
  await page.locator("#editButton").click();
  await page.locator("#addLayer").click();
  await addFrom(page, "builtin");
  await page.locator('#packages [data-overlay="roads"]').click();
  await page.locator("#addPackages").click();
  await expect.poll(() => cloud.asked.filter((each) => each.endpoint === "records/modify").length).toBe(1);
  const [listing] = await calls();
  expect(listing.request).toMatchObject({ id: TATRAS, pieces: [] });
  const [apply] = await asks();
  expect(apply.edit).toEqual({ addPackages: "roads" });
});
